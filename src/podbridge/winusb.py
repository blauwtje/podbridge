"""Bind WinUSB to the Bluetooth radio for the app's lifetime and give the Realtek driver back after."""
import atexit
import json
import os
import re
import subprocess
import sys
import time
from contextlib import contextmanager
from dataclasses import dataclass, field
from functools import partial
from pathlib import Path
from typing import Callable

from bumble.drivers.rtk import RTK_USB_PRODUCTS

from podbridge.paths import install_dir

POLL_SECONDS = 10.0
POLL_INTERVAL = 0.5
COMMAND_TIMEOUT = 120
CTRL_CLOSE_EVENT = 2
INF_RE = re.compile(r"oem\d{1,5}\.inf", re.IGNORECASE)
INSTANCE_RE = re.compile(r"USB\\VID_([0-9A-F]{4})&PID_([0-9A-F]{4})\\[A-Z0-9&_.]{1,64}", re.IGNORECASE)
LIBWDI_PROVIDER = "libwdi"
REMOVE_CERT_SCRIPT = (
    "foreach ($store in 'Root','TrustedPublisher') { "
    "Get-ChildItem \"Cert:\\LocalMachine\\$store\" | "
    "Where-Object { $_.Subject -like '*libwdi autogenerated*' } | Remove-Item }"
)


class DriverError(RuntimeError):
    pass


def run_command(args: list[str]) -> subprocess.CompletedProcess:
    return subprocess.run(args, capture_output=True, text=True, timeout=COMMAND_TIMEOUT, check=False)


@dataclass
class Machine:
    runner: Callable[[list[str]], subprocess.CompletedProcess] = run_command
    state_path: Path = field(default_factory=lambda: install_dir() / "state" / "driver-state.json")
    wdi_simple: Path = field(default_factory=lambda: install_dir() / "tools" / "wdi-simple.exe")
    sleep: Callable[[float], None] = time.sleep


def run_checked(machine: Machine, args: list[str]) -> str:
    result = machine.runner(args)
    if result.returncode != 0:
        raise DriverError(f"{Path(args[0]).name} {' '.join(args[1:2])} failed with exit code {result.returncode}")
    return result.stdout or ""


def record_blocks(text: str, keys: str) -> list[dict[str, str]]:
    blocks = []
    for chunk in re.split(r"\n\s*\n", text):
        fields = re.findall(rf"^({keys}):\s*(\S.*?)\s*$", chunk, re.MULTILINE)
        if fields:
            blocks.append(dict(reversed(fields)))
    return blocks


def find_instance(machine: Machine, vid: int, pid: int) -> str:
    prefix = f"USB\\VID_{vid:04X}&PID_{pid:04X}\\".upper()
    out = run_checked(machine, ["pnputil", "/enum-devices", "/connected"])
    for block in record_blocks(out, "Instance ID|Driver Name"):
        instance_id = block.get("Instance ID", "")
        if instance_id.upper().startswith(prefix) and INSTANCE_RE.fullmatch(instance_id):
            return instance_id
    raise DriverError(f"no connected USB device {vid:04X}:{pid:04X}")


def current_driver(machine: Machine, instance_id: str) -> str | None:
    out = run_checked(machine, ["pnputil", "/enum-devices", "/instanceid", instance_id, "/drivers"])
    match = re.search(r"^Driver Name:\s*(\S+)\s*$", out, re.MULTILINE)
    return match.group(1) if match else None


def is_realtek(vid: int, pid: int) -> bool:
    return (vid, pid) in RTK_USB_PRODUCTS


def driver_provider(machine: Machine, inf: str) -> str | None:
    out = run_checked(machine, ["pnputil", "/enum-drivers"])
    for block in record_blocks(out, "Published Name|Provider Name"):
        if block.get("Published Name", "").lower() == inf.lower():
            return block.get("Provider Name")
    return None


def check_libwdi(machine: Machine, inf: str) -> None:
    provider = driver_provider(machine, inf)
    if provider is None or provider.lower() != LIBWDI_PROVIDER:
        raise DriverError(f"{inf} is not a {LIBWDI_PROVIDER} driver (provider {provider}); driver-state.json kept")


def check_state(state: object) -> dict:
    if not isinstance(state, dict) or set(state) != {"instance_id", "original_inf", "libwdi_inf"}:
        raise DriverError("driver-state.json has the wrong fields")
    match = INSTANCE_RE.fullmatch(str(state["instance_id"]))
    if not match:
        raise DriverError("driver-state.json has an invalid instance ID")
    if not is_realtek(int(match.group(1), 16), int(match.group(2), 16)):
        raise DriverError("driver-state.json names a device outside Bumble's rtk table")
    infs = [state["original_inf"], state["libwdi_inf"]]
    if not all(inf is None or (isinstance(inf, str) and INF_RE.fullmatch(inf)) for inf in infs):
        raise DriverError("driver-state.json has an invalid driver INF")
    if state["libwdi_inf"] is not None and str(state["libwdi_inf"]).lower() == str(state["original_inf"]).lower():
        raise DriverError("driver-state.json names the original driver as the WinUSB driver")
    return state


def refuse_link(path: Path) -> None:
    if path.is_symlink():
        raise DriverError(f"{path} is a link; refusing to use it")


def read_state(path: Path) -> dict | None:
    refuse_link(path)
    if not path.exists():
        return None
    try:
        return check_state(json.loads(path.read_text(encoding="utf-8")))
    except (OSError, ValueError) as exc:
        raise DriverError(f"cannot read {path.name}: {exc}") from exc


def write_state(path: Path, state: dict) -> None:
    refuse_link(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_name(path.name + ".tmp")
    refuse_link(tmp)
    tmp.write_text(json.dumps(check_state(state)), encoding="utf-8")
    os.replace(tmp, path)


def wait_for(machine: Machine, instance_id: str, done: Callable[[str | None], bool]) -> str | None:
    for _ in range(int(POLL_SECONDS / POLL_INTERVAL)):
        driver = current_driver(machine, instance_id)
        if done(driver):
            return driver
        machine.sleep(POLL_INTERVAL)
    driver = current_driver(machine, instance_id)
    return driver if done(driver) else None


def bind(machine: Machine, vid: int, pid: int) -> None:
    if not is_realtek(vid, pid):
        raise DriverError(f"USB device {vid:04X}:{pid:04X} is not in Bumble's rtk table; refusing to bind WinUSB")
    instance_id = find_instance(machine, vid, pid)
    original = current_driver(machine, instance_id)
    state = {"instance_id": instance_id, "original_inf": original, "libwdi_inf": None}
    write_state(machine.state_path, state)
    args = [str(machine.wdi_simple), "--vid", f"0x{vid:04X}", "--pid", f"0x{pid:04X}", "--type", "0", "--silent"]
    run_checked(machine, args)
    libwdi = wait_for(machine, instance_id, lambda d: bool(d) and d != original and bool(INF_RE.fullmatch(d)))
    if libwdi is None:
        raise DriverError(f"device {instance_id} did not switch to WinUSB within {POLL_SECONDS:.0f} s")
    write_state(machine.state_path, {**state, "libwdi_inf": libwdi})


def is_restored(state: dict, driver: str | None) -> bool:
    if driver is None:
        return False
    if state["libwdi_inf"] is None:
        return driver == state["original_inf"]
    return driver.lower() != state["libwdi_inf"].lower()


def restore_driver(machine: Machine) -> None:
    state = read_state(machine.state_path)
    if state is None:
        return
    instance_id, libwdi = state["instance_id"], state["libwdi_inf"]
    if libwdi is not None:
        check_libwdi(machine, libwdi)
    driver = current_driver(machine, instance_id)
    if driver is None:
        raise DriverError(f"device {instance_id} not found; driver-state.json kept for the next restore")
    if libwdi is not None and driver.lower() == libwdi.lower():
        run_checked(machine, ["pnputil", "/delete-driver", libwdi, "/uninstall", "/force"])
    run_checked(machine, ["pnputil", "/scan-devices"])
    if wait_for(machine, instance_id, lambda d: is_restored(state, d)) is None:
        raise DriverError(f"device {instance_id} still uses WinUSB; driver-state.json kept")
    machine.state_path.unlink()


def remove_cert(machine: Machine) -> None:
    """Delete the libwdi root certificate (`podbridge restore --remove-cert`, Decision 19)."""
    run_checked(machine, ["powershell.exe", "-NoProfile", "-NonInteractive", "-Command", REMOVE_CERT_SCRIPT])


def install_close_handler(restore: Callable[[], None]) -> object:
    if sys.platform != "win32":
        return None
    import ctypes

    @ctypes.WINFUNCTYPE(ctypes.c_int, ctypes.c_uint)
    def handler(event: int) -> int:
        if event == CTRL_CLOSE_EVENT:
            restore()
        return 0

    ctypes.windll.kernel32.SetConsoleCtrlHandler(handler, True)
    return handler


def remove_close_handler(handler: object) -> None:
    if handler is not None:
        import ctypes
        ctypes.windll.kernel32.SetConsoleCtrlHandler(handler, False)


@contextmanager
def bound(vid: int, pid: int, machine: Machine | None = None):
    machine = machine or Machine()
    restore_driver(machine)
    restore = partial(restore_driver, machine)
    atexit.register(restore)
    handler = install_close_handler(restore)
    try:
        bind(machine, vid, pid)
        yield machine
    finally:
        remove_close_handler(handler)
        atexit.unregister(restore)
        restore_driver(machine)


def restore_main(args, machine: Machine | None = None) -> int:
    """`podbridge restore [--remove-cert]`: give the device back to its original driver.

    With `--remove-cert` (args.remove_cert) it also deletes the libwdi certificate,
    even when the driver restore fails. Returns 1 if any step failed.
    """
    machine = machine or Machine()
    steps = [restore_driver] + ([remove_cert] if getattr(args, "remove_cert", False) else [])
    failed = False
    for step in steps:
        try:
            step(machine)
        except DriverError as exc:
            print(f"podbridge restore: {exc}", file=sys.stderr)
            failed = True
    return 1 if failed else 0
